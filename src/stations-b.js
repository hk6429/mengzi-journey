export function buildStationsB(i, P) {
  const {box, person, tree} = P;
  if (i === 3) {
    // 補上橋樑結構與待用木料。
    for (const z of [-.82, .82]) {
      box(-.25, .12, z, 5.8, .12, .14, '#654b36');
      for (const x of [-2.5, -.7, 1.1, 2.5]) box(x, .3, z, .12, .75, .12, '#76563d');
      box(-.25, 1, z, 5.2, .1, .1, '#76563d');
    }
    if(P.slips) P.slips(1.94,.87,-2,1.35);
    else for (const z of [-2.25, -1.75]) box(1.94, .87, z, 1.35, .025, .025, '#72543a');
    box(3.4, 0, 1.5, 1.1, .1, .25, '#a47a50');
    box(3.4, .12, 1.8, 1.1, .1, .25, '#a47a50');
    tree(-3.8, -2.4);
  }
  if (i === 4) {
    if(P.slips) P.slips(-2,.79,0,1.2);
    else {
    for (let n = 0; n < 6; n++) box(-2.52 + n * .2, .79, 0, .16, .035, .55, '#d2bb87');
    for (const z of [-.18, .18]) box(-2, .83, z, 1.15, .025, .025, '#76543b');
    }
    box(-2, 0, 1.1, .7, .18, .5, '#94744d');
    box(-3.4, 0, -1.8, .15, 1.45, .15, '#76543b');
    box(-3.4, 1.45, -1.8, .55, .12, .4, '#c6a66f');
    // 岔路以地面色塊提示不同的選擇。
    box(-.6, .01, 2.6, 1.1, .025, 1.8, '#c4ae86');
    box(-1.65, .01, 1.7, 1, .025, .65, '#c4ae86');
    box(.45, .01, 1.7, 1, .025, .65, '#c4ae86');
    tree(3.7, .8);
  }
  if (i === 5) {
    for (let n = 0; n < 5; n++) {
      const x = -3 + n * 1.5;
      box(x, 1.4, -2, .72, .35, .8, '#a28b68');
    }
    box(-3.8, 0, -2, .35, 1.9, 1.05, '#9e8968');
    box(3.8, 0, -2, .35, 1.9, 1.05, '#9e8968');
    box(1, 0, -.8, 1.6, .55, .75, '#77543b');
    box(1, .55, -.8, 1.8, .1, .9, '#9c7851');
    box(.7, .65, -.8, .75, .04, .45, '#dbc392');
    person(2.5, .25, '#88715c');
    box(-2.5, .01, 1.8, 2.4, .025, 1.1, '#c5af87');
  }
}
