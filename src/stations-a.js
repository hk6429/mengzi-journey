// 以簡化地景提示典故，不重建特定年代的器物造型。
export function buildStationsA(i, {box, tree}) {
  if (i === 0) {
    // 田埂、灌溉溝與散置的築牆工具。
    box(-2, 0, 2.15, 3.4, .14, .22, '#92744c');
    box(-4.15, 0, 0, .36, .06, 4.5, '#779995');
    for (let n = 0; n < 3; n++) box(-4.15, .06, -1.5 + n * 1.4, .55, .06, .12, '#b3b4a0');
    box(2.5, 0, -2.4, 2.3, .15, .2, '#74503a');
    box(2.5, 1.45, -2.4, 2.3, .15, .2, '#74503a');
    box(1.25, 0, -.85, .12, 1.2, .12, '#77583b');
    box(1.25, 1.12, -.85, .48, .12, .2, '#77583b');
    box(3.9, 0, -.5, .75, .2, .6, '#9a7350');
    tree(-4.8, -2.6);
  } else if (i === 1) {
    // 棚架、魚鹽攤與海岸；牢獄以木柵暗示。
    for (const x of [-3.55, -.75]) box(x, 0, .1, .11, 1.8, .11, '#6f513a');
    box(-2.15, 1.8, .1, 3.1, .14, 1.2, '#a67c51');
    for (let n = 0; n < 4; n++) box(-3.3 + n * .7, 1.95, .1, .08, .08, 1.25, '#dbc29a');
    for (let n = 0; n < 3; n++) box(-3.1 + n * .27, .94, 0, .2, .08, .12, '#a6bec0');
    box(-1.8, .92, 0, .42, .18, .38, '#e9dec4');
    box(.78, 0, -1.5, .1, 1.5, .1, '#594337');
    box(.4, 1.4, -1.5, .85, .1, .12, '#594337');
    box(.4, .05, -1.5, .85, .1, .12, '#594337');
    box(3, .04, .65, 2.1, .05, .4, '#d5c49c');
    for (let n = 0; n < 3; n++) box(2.35 + n * .65, .05, -1.4 + n * .6, .45, .025, .05, '#bed4cb');
    box(-4.25, 0, 1.25, .55, .3, .55, '#94714f');
    box(-4.25, .3, 1.25, .62, .08, .62, '#c2a078');
  } else if (i === 2) {
    // 山路沿途的碎石、土階與繩束行囊。
    for (let n = 0; n < 7; n++) {
      box(-3.5 + n * .9, 0, .55 - n * .18, .7, .09 + n * .025, .42, '#a89980');
      box(-3.7 + n * .9, 0, -.15 - n * .18, .2, .16, .18, '#766f63');
    }
    box(2, .12, -.75, .75, .06, .08, '#d1b788');
    box(2, .45, -.75, .75, .06, .08, '#d1b788');
    box(2, .12, -.73, .07, .65, .08, '#d1b788');
    for (let n = 0; n < 3; n++) box(3.25 + n * .35, 0, -2.5, .24, .8 + n * .25, .24, '#716b5d');
    tree(-4.5, -3.2);
  }
}
